import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/Admin/AppData/Local/ms-playwright/chromium-1200/chrome-win64/chrome.exe'});
const errors=[];
const base=process.argv[2]||'http://127.0.0.1:5180/';
async function load(page,name,mode){
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base,{waitUntil:'networkidle',timeout:120000});
  assert.ok(await page.locator('#session-entry').isVisible());
  await page.locator('#player-name').fill(name);
  await page.locator(`.session-modes [value="${mode}"]`).click();
  await page.locator('#scene-loading').waitFor({state:'hidden',timeout:120000});
  await page.evaluate(async()=>{window.testGame=(await import(document.querySelector('script[src*="/src/main.js"]').src)).game;});
}
try {
  const a=await browser.newPage({viewport:{width:1280,height:800}});
  let websockets=0;a.on('websocket',socket=>{if(new URL(socket.url()).pathname==='/online')websockets++;});
  await load(a,'Cún An','explore');
  assert.equal(websockets,0);
  assert.equal(await a.evaluate(()=>testGame.bike.playerName),'Cún An');
  assert.equal(await a.evaluate(()=>testGame.bike.identity.parent===testGame.bike.rider),true);
  await a.locator('#session-panel button').click();
  await a.locator('.session-modes [value="online"]').click();
  await a.waitForFunction(()=>testGame.online?.client.status==='connected');
  const b=await browser.newPage({viewport:{width:844,height:390},isMobile:true,hasTouch:true});
  await load(b,'Cún Bình','online');
  await b.waitForFunction(()=>testGame.online?.client.status==='connected');
  await a.waitForFunction(()=>testGame.online.avatars.entries.size===1&&[...testGame.online.avatars.entries.values()][0].bike.visible);
  await b.waitForFunction(()=>testGame.online.avatars.entries.size===1&&[...testGame.online.avatars.entries.values()][0].bike.visible);
  const originalId=await a.evaluate(()=>testGame.online.client.id);
  await a.evaluate(()=>testGame.online.client.socket.close(4000,'Simulated disconnect'));
  await a.waitForFunction(()=>testGame.online.client.status==='reconnecting');
  assert.equal(await a.evaluate(()=>testGame.online.canMove),false);
  await a.waitForFunction(()=>testGame.online.client.status==='connected');
  assert.equal(await a.evaluate(()=>testGame.online.client.id),originalId);
  await a.evaluate(()=>{testGame.traffic.enabled=false;});
  await b.evaluate(()=>{testGame.traffic.enabled=false;});
  await a.waitForTimeout(2200);
  await a.keyboard.down('w');
  await a.waitForFunction(()=>testGame.crashCount>0,{},{timeout:10000});
  await a.keyboard.up('w');
  assert.ok(await b.evaluate(()=>testGame.crashCount>0));
  await a.waitForFunction(()=>testGame.audio.collisionVoice?.lastPlayed?.type==='player');
  await b.waitForFunction(()=>testGame.audio.collisionVoice?.lastPlayed?.type==='player');
  assert.ok((await a.locator('#collision-message').textContent()).includes('Cún Bình'));
  assert.ok((await b.locator('#collision-message').textContent()).includes('Cún An'));
  const before=await a.evaluate(()=>({region:testGame.world.region.id,crashes:testGame.crashCount,remote:testGame.online.avatars.entries.size}));
  await a.locator('[data-district="south-bank"]').click();
  await a.waitForFunction(()=>testGame.world.region.id==='south-bank'&&!testGame.isLoadingRegion&&testGame.online.canMove,{},{timeout:120000});
  await a.waitForFunction(()=>[...testGame.online.avatars.entries.values()].every(e=>!e.bike.visible));
  assert.equal(await a.evaluate(()=>testGame.online.avatars.root.parent===testGame.scene),true);
  assert.equal(await a.evaluate(()=>testGame.online.avatars.entries.values().next().value.bike.children.length>0),true);
  await a.locator('#session-panel button').click();
  await a.locator('.session-modes [value="explore"]').click();
  assert.equal(await a.evaluate(()=>testGame.online),null);
  assert.equal(await a.evaluate(()=>testGame.session.mode),'explore');
  await a.reload({waitUntil:'networkidle'});
  assert.ok(await a.locator('#session-entry').isVisible());
  assert.deepEqual(errors,[]);
  await b.screenshot({path:new URL('./online-mobile.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1')});
  console.log('ONLINE_BROWSER_PASS',JSON.stringify({before,twoPlayersVisible:true,reconnectSameId:true,bothReceiveCollision:true,regionIsolation:true,switchToExplore:true,nameRequiredOnReload:true,errors}));
} finally {await browser.close();}
